import assert from 'node:assert/strict';
import test from 'node:test';
import { checkSopFreeze } from '../../business-docs/08-工具/check_customer_agent_sop_freeze.mjs';
import { buildSopExportPreparation, checkSopExportPreparation } from '../../business-docs/08-工具/prepare_customer_agent_sop_export.mjs';
import { checkSopSideExport } from '../../business-docs/08-工具/export_customer_agent_sop_side.mjs';

test('SOP freeze record matches the generated bytes and keeps export closed', () => {
  const result = checkSopFreeze();
  assert.equal(result.status, 'FROZEN_NOT_EXPORTED');
  assert.equal(result.profile, 'content-intake-legacy-check-v1');
  assert.equal(result.openapi, '82443864e4459af4a9575b304ccecfcbb2cbb4e3c1f08cff13bd512616fe54b0');
  assert.equal(result.schema, '1c0a4e508ea0aab97d40abff4829ea5a0ce65882ad6a044187fc231872bbe39c');
});

test('SOP export preparation stays beside the current profile and is not an export receipt', () => {
  const parsed = checkSopExportPreparation();
  assert.equal(parsed.status, 'PREPARED_NOT_EXPORTED');
  assert.equal(parsed.exportApproved, false);
  assert.equal(parsed.currentProfile, 'content-intake-legacy-check-v1');
  assert.equal(parsed.sopProfileInExporterAllowlist, false);
  assert.equal(parsed.productMigration, null);
  assert.equal(JSON.parse(buildSopExportPreparation()).openapi.sha256, parsed.openapi.sha256);
});

test('SOP side export records the frozen bytes without intake or the main contract set', () => {
  const parsed = checkSopSideExport();
  assert.equal(parsed.status, 'SIDE_EXPORTED_NOT_INTAKE');
  assert.equal(parsed.mainContractSetExported, false);
  assert.equal(parsed.intakeApproved, false);
  assert.equal(parsed.productionConsumerReady, false);
  assert.equal(parsed.productMigration, null);
  assert.equal(parsed.openapi.sha256, '82443864e4459af4a9575b304ccecfcbb2cbb4e3c1f08cff13bd512616fe54b0');
});

test('SOP freeze check rejects an export allowlist or a switched profile', () => {
  const files = new Map();
  const read = file => {
    if (files.has(file)) return Buffer.from(files.get(file));
    throw new Error(`missing ${file}`);
  };
  files.set('business-docs/01-客服Agent项目/90-评审/2026-10-10_SOP合同冻结批准.md', 'FROZEN · NOT EXPORTED · NOT INTAKE\n本批准不授权 export\nSHA-256 `aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa`\n**批准 schema 1.26：**\nSHA-256 `bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb`\n');
  files.set('business-docs/01-客服Agent项目/30-开发-进行中/openapi.v1.23.yaml', 'openapi');
  files.set('business-docs/01-客服Agent项目/30-开发-进行中/schema.v1.26.sql', 'schema');
  files.set('business-docs/01-客服Agent项目/30-开发-进行中/contract-profile.v1.json', '{"schema":"customer-agent-contract-profile/v1","profile":"content-intake-sop-xlsx-v1"}');
  files.set('business-docs/08-工具/export_customer_agent_contract_set.mjs', 'content-intake-legacy-check-v1');
  assert.throws(() => checkSopFreeze(read), /当前合同 profile/);
});
