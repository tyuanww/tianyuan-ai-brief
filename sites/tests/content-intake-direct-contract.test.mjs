import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import Ajv from 'ajv/dist/2020.js';
import { buildIntakeDirectContractFiles, buildIntakeManagementContractFiles, INTAKE_DIRECT_CONTRACT_PATHS, INTAKE_DIRECT_SOURCES, INTAKE_MANAGEMENT_CONTRACT_PATHS } from '../../business-docs/08-工具/build_customer_agent_backend_contract.mjs';
const read = file => readFileSync(new URL('../../'+file, import.meta.url));
const digest = data => createHash('sha256').update(data).digest('hex');
const generated = buildIntakeDirectContractFiles(read), previous = buildIntakeManagementContractFiles(read);
const delta = JSON.parse(read(INTAKE_DIRECT_SOURCES.openapi));
const schemasFrom = bytes => Object.fromEntries(bytes.toString().split('\n').filter(line => /^    Intake[A-Za-z0-9]+: /.test(line)).map(line => { const i=line.indexOf(': ');return [line.slice(4,i),JSON.parse(line.slice(i+2))]; }));
const pathsFrom = bytes => Object.fromEntries(bytes.toString().split('\n').filter(line => /^  "\/v1\/intake\//.test(line)).map(line => { const i=line.indexOf(': ');return [JSON.parse(line.slice(2,i)),JSON.parse(line.slice(i+2))]; }));
const schemas=schemasFrom(generated.openapi), paths=pathsFrom(generated.openapi);
const ajv=new Ajv({strict:true,allowUnionTypes:true});ajv.addKeyword('components');ajv.addFormat('date-time',v=>Number.isFinite(Date.parse(v)));
ajv.addSchema({$id:'urn:synthetic:direct',components:{schemas}});
const validate=name=>ajv.compile({$ref:`urn:synthetic:direct#/components/schemas/${name}`});
const key={candidateId:'candidate-a',version:1,digest:'a'.repeat(64)};
const publish={operationId:'operation-a',key,baseReleaseId:null,sourceEvidenceVersion:1,title:'合成发布',summary:'合成说明',confirmed:true};
const rollback={operationId:'rollback-a',baseReleaseId:'release-b',targetReleaseId:'release-a',impactDigest:'a'.repeat(64),rollbackPlanId:'plan-a',confirmed:true};
test('generated bytes are reproducible, preserve exact frozen predecessor and unrelated wire',()=>{
 for(const kind of ['openapi','database']) assert.ok(generated[kind].equals(read(INTAKE_DIRECT_CONTRACT_PATHS[kind])));
 assert.equal(digest(read(INTAKE_MANAGEMENT_CONTRACT_PATHS.openapi)),'ef4e6df57d9ba934827a2315329aea2e473e12e577441011b78b706243251d38');
 assert.equal(digest(previous.database),'5f958e4f7dcde7e11f9a6d38d8339b96654517209a493776acbfc7c3f5202013');
 assert.ok(generated.database.includes(previous.database));
 for(const [name,schema] of Object.entries(schemasFrom(previous.openapi))) if(!delta.components.schemas[name]) assert.deepEqual(schemas[name],schema,name);
 for(const [route,item] of Object.entries(pathsFrom(previous.openapi))) if(!delta.paths[route]) assert.deepEqual(paths[route],item,route);
 assert.match(generated.openapi.toString(),/x-content-intake-direct-development: .*"status":"DRAFT".*"runtime_activated":false.*"exportApproved":false/);
});
test('all generated schemas compile for a standard consumer',()=>{for(const name of Object.keys(schemas)) validate(name);});
test('publish and corrective rollback require explicit true; approval or authority cannot be forged',()=>{
 for(const [name,body] of [['IntakePublish',publish],['IntakeRollback',rollback]]) {
  const valid=validate(name);assert.ok(valid(JSON.parse(JSON.stringify(body))),JSON.stringify(valid.errors));
  for(const confirmed of [undefined,false,'true',1,null]) assert.equal(valid({...body,confirmed}),false);
  for(const extra of [{approvalEvidenceVersion:1},{publicationPolicy:'direct-v1'},{actorId:'director'},{skipApproval:true}]) assert.equal(valid({...body,...extra}),false);
 }
});
test('direct candidate exposes server policy and cannot pretend to carry approval',()=>{
 const body={key,sourceId:'source-a',state:'awaiting-evidence',readinessReasons:[],sourceEvidenceVersion:0,approvalEvidenceVersion:0,revocationGeneration:0,createdAt:'2026-10-08T00:00:00Z',updatedAt:'2026-10-08T00:00:00Z',publishedReleaseId:null,publicationPolicy:'direct-v1'};
 const valid=validate('IntakeCandidate');assert.ok(valid(body),JSON.stringify(valid.errors));
 assert.equal(valid({...body,approvalEvidenceVersion:1}),false);
 assert.equal(valid({...body,publicationPolicy:undefined}),false);
 assert.equal(valid({...body,publicationPolicy:'forged'}),false);
 assert.ok(valid({...body,publicationPolicy:'approval-v1',approvalEvidenceVersion:1}));
});
test('changed operations preserve security, errors and operation IDs; review mutations are deprecated',()=>{
 const old=pathsFrom(previous.openapi);
 for(const [route,item] of Object.entries(delta.paths)) {
  const op=paths[route].post;assert.deepEqual(op.security,[{ProductSession:[]}]);
  assert.equal(op.operationId,old[route].post.operationId);
  const expectedResponses=Object.fromEntries(Object.entries(old[route].post.responses).filter(([code])=>!route.includes('/review') || !code.startsWith('2')));
  assert.deepEqual(op.responses,expectedResponses);
  if (route.includes('/review')) assert.equal(Object.keys(op.responses).some(code=>code.startsWith('2')),false);
  if(route.includes('/review')) {assert.equal(op.deprecated,true);assert.equal(op['x-direct-profile-read-only'],true);}
 }
});
test('generator rejects missing routes, wrong verbs and unrelated schema changes',()=>{
 for(const mutate of [d=>delete d.paths[Object.keys(d.paths)[0]],d=>{const p=Object.keys(d.paths)[0];d.paths[p].delete=d.paths[p].post;},d=>{d.components.schemas.Forged={type:'string'};}]) {
  const changed=structuredClone(delta);mutate(changed);
  assert.throws(()=>buildIntakeDirectContractFiles(file=>file===INTAKE_DIRECT_SOURCES.openapi?Buffer.from(JSON.stringify(changed)):read(file)),/Unexpected direct/);
 }
});
